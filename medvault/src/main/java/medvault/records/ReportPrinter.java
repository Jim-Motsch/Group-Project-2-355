package medvault.records;

import java.io.IOException;
import java.io.OutputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Objects;
import java.util.concurrent.TimeUnit;

/**
 * Converts an exported HTML chart to PDF using an external command-line tool
 * ({@code wkhtmltopdf}).
 *
 * <p><b>CWE-78: OS Command Injection.</b> If a command were built as one
 * string and handed to a shell ({@code sh -c}, {@code cmd /c}), a file name
 * such as {@code x.html; rm -rf ~} would run a second command. Here the
 * command is a fixed argument list given to {@link ProcessBuilder}, which
 * starts the program directly with no shell, so {@code ;}, {@code |},
 * {@code &} and {@code $( )} are just characters in an argument. The only
 * variable arguments are two absolute, normalized paths that the server
 * created (never user text); being absolute, they can't start with
 * {@code -} and be read as an option either. The output file name is
 * generated by the server. JavaScript and local-file access are switched off
 * inside the converter as well.</p>
 *
 * <p>If {@code wkhtmltopdf} is not installed, {@link #toPdf} throws an
 * {@link IllegalStateException} that says so.</p>
 *
 * @author James Strickert
 */
public class ReportPrinter {

    /** The converter program, looked up on the PATH. Fixed; never taken from input. */
    static final String TOOL = "wkhtmltopdf";
    /** Longest a conversion may run before it is killed. */
    static final long TIMEOUT_SECONDS = 60;

    /**
     * @param htmlFile exported chart (a server-created temp file)
     * @param outDir   directory for the PDF
     * @return path of the generated PDF
     * @throws IllegalStateException if {@code wkhtmltopdf} is not installed, fails or times out
     */
    public Path toPdf(Path htmlFile, Path outDir) {
        Objects.requireNonNull(htmlFile, "htmlFile");
        Objects.requireNonNull(outDir, "outDir");
        if (!Files.isRegularFile(htmlFile)) {
            throw new IllegalArgumentException("htmlFile must be an existing file");
        }
        Path pdf;
        try {
            // Server-generated, unpredictable output name, created owner-only on POSIX.
            pdf = Files.createTempFile(outDir, "chart-", ".pdf");
        } catch (IOException e) {
            throw new UncheckedIOException("could not create the PDF file", e);
        }
        boolean ok = false;
        try {
            Process process;
            try {
                process = new ProcessBuilder(command(htmlFile, pdf))
                        .redirectErrorStream(true)
                        .redirectOutput(ProcessBuilder.Redirect.DISCARD)
                        .start();
            } catch (IOException notInstalled) {
                throw new IllegalStateException(TOOL + " is not installed or not on the PATH; "
                        + "install it to export charts as PDF", notInstalled);
            }
            try (OutputStream stdin = process.getOutputStream()) {
                // Nothing to send; closing stdin releases the pipe (CWE-772).
            }
            if (!process.waitFor(TIMEOUT_SECONDS, TimeUnit.SECONDS)) {
                process.destroyForcibly();
                throw new IllegalStateException(TOOL + " timed out");
            }
            if (process.exitValue() != 0) {
                throw new IllegalStateException(TOOL + " failed with exit code " + process.exitValue());
            }
            ok = true;
            return pdf;
        } catch (IOException e) {
            throw new UncheckedIOException("PDF conversion failed", e);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("PDF conversion interrupted", e);
        } finally {
            if (!ok) {
                deleteQuietly(pdf);
            }
        }
    }

    /**
     * Builds the exact argument list passed to {@link ProcessBuilder}: the tool,
     * fixed options, and two absolute server-side paths. No shell, no user text.
     *
     * @param htmlFile input file
     * @param pdfFile  output file
     * @return an immutable argument list
     */
    List<String> command(Path htmlFile, Path pdfFile) {
        Path in = htmlFile.toAbsolutePath().normalize();
        Path out = pdfFile.toAbsolutePath().normalize();
        Path inDir = in.getParent();
        return List.of(TOOL,
                "--quiet",
                "--disable-javascript",
                "--disable-local-file-access",
                "--allow", inDir.toString(),
                in.toString(),
                out.toString());
    }

    private static void deleteQuietly(Path p) {
        try {
            Files.deleteIfExists(p);
        } catch (IOException ignored) {
            // best effort; the file is empty and in a server-owned directory
        }
    }
}
